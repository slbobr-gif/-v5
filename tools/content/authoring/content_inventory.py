def ev(id_, zone, tags, art, title, text, choices, when=None):
    e = {"id": id_, "kind": "random", "zone": zone, "tags": tags, "once": False, "art": art, "creature": None,
         "title": title, "text": text, "choices": choices}
    if when:
        e["whenHas"] = when
    return e


def ch(id_, text, risk, outs, req=None):
    c = {"id": id_, "text": text, "risk": risk, "outcomes": [{"weight": w, "text": t, "effects": e} for w, t, e in outs]}
    if req:
        c["requires"] = req
    return c


