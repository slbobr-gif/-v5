def _ital(text, old, new):
    a, b = f"_{old}_", f"_{new}_"
    if a in text:
        return text.replace(a, b)
    return text


def main():
    qp = os.path.join(CONTENT, "quests.json")
    quests = json.load(open(qp, encoding="utf-8"))
    for q in quests:
        if q.get("kind") != "folklore":
            continue
        for st in q["steps"]:
            if "event" in st:
                e = st["event"]
                if e["id"] in HINTS:
                    e["text"] = _ital(e["text"], *HINTS[e["id"]])
                for c in e["choices"]:
                    t = CHOICE_TEXT.get((e["id"], c["id"]))
                    if t:
                        c["text"] = t
                x = EXTRA.get(e["id"])
                if x and all(c["id"] != x["id"] for c in e["choices"]):
                    e["choices"].append(x)
                e["choices"].sort(key=lambda c: hashlib.md5(f"{e['id']}:{c['id']}".encode()).hexdigest())
            else:
                kind_t, cun_t = THRESHOLDS[q["id"]]
                br = st["branches"]
                if len(br) >= 2 and "favor" in br[0].get("if", {}):
                    br[0]["if"]["favor"] = f">={kind_t}"
                    br[1]["if"]["favor"] = f">={cun_t}"
    with open(qp, "w", encoding="utf-8") as f:
        json.dump(quests, f, ensure_ascii=False, indent=2)
        f.write("\n")
    for name, omens in (("events_ch1.json", OMENS_CH1), ("events_ch2.json", OMENS_CH2)):
        p = os.path.join(CONTENT, name)
        evs = json.load(open(p, encoding="utf-8"))
        evs = [e for e in evs if not e["id"].startswith("omen_")] + omens
        with open(p, "w", encoding="utf-8") as f:
            json.dump(evs, f, ensure_ascii=False, indent=2)
            f.write("\n")
    print("spirits v2: шаги +4-й вариант, подсказки убраны (кроме лешего), пороги выше, предупреждений",
          len(OMENS_CH1) + len(OMENS_CH2))


if __name__ == "__main__":
    main()
